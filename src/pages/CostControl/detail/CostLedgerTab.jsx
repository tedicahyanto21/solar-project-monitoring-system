import { useEffect, useState } from 'react';
import {
  Box, Stack, Typography, Paper, Button, Chip, Dialog, DialogTitle, DialogContent, DialogActions,
  TextField, MenuItem, Alert,
} from '@mui/material';
import AddRoundedIcon from '@mui/icons-material/AddRounded';
import {
  getCostTransactions, createCostTransaction, updateDraftCostTransaction, checkDuplicateTransaction, postCostTransaction, voidCostTransaction,
} from '../../../services/repositories/costRepository';
import { parseAmount } from '../../../services/costTransactionEdit';
import { useAuth } from '../../../context/AuthContext';
import { ROLES } from '../../../constants/roles';

// B2: Actual Cost input authority. C-01D.1 Payment Projection Batch:
// FINANCE removed -- Finance no longer creates a generic Cost/
// PAYMENT_ONLY transaction from this dialog at all. Finance's only entry
// point is now marking an existing Payment Projection (a batch of Cost
// Transactions SCM selected) PENDING -> PAID in PaymentProjectionTab.jsx;
// the settlement PAYMENT_ONLY record is generated by the system as a side
// effect, never created directly by Finance. SUPER_ADMIN retains this
// administrative flow unchanged, including the isFinance
// PAYMENT_ONLY-settles-a-cost sub-flow below, which was never
// Finance-exclusive to begin with.
const CAN_CREATE = [ROLES.SUPER_ADMIN, ROLES.SCM, ROLES.HC];
const STATUS_COLOR = { DRAFT: 'default', POSTED: 'success', VOID: 'error' };
const CATEGORIES = ['Material Purchase', 'Procurement', 'Vendor Payment', 'Accommodation', 'Transportation', 'Milestone Payment', 'Other'];

const EMPTY = { category: 'Material Purchase', description: '', amount: '', transactionDate: new Date().toISOString().slice(0, 10), referenceNumber: '', invoiceNumber: '', transactionType: 'COST', relatedTransactionId: '' };

export default function CostLedgerTab({ projectId, onDataChanged }) {
  const { profile } = useAuth();
  const canCreate = CAN_CREATE.includes(profile?.role);
  const isFinance = profile?.role === 'FINANCE' || profile?.role === 'SUPER_ADMIN';
  const [transactions, setTransactions] = useState([]);
  const [open, setOpen] = useState(false);
  const [form, setForm] = useState(EMPTY);
  const [editing, setEditing] = useState(null); // transactionId of the Draft being edited, or null for "new"
  const [formError, setFormError] = useState('');
  const [duplicate, setDuplicate] = useState({ level: null, reasons: [] });
  const [error, setError] = useState('');
  const [voidTarget, setVoidTarget] = useState(null);
  const [voidReason, setVoidReason] = useState('');

  function load() {
    getCostTransactions(projectId).then(setTransactions);
  }
  useEffect(load, [projectId]);

  // Existing COST transactions a PAYMENT_ONLY entry could settle -- only
  // POSTED ones, since a DRAFT/VOID entry isn't a real recorded cost yet.
  const settleableTransactions = transactions.filter((t) => t.status === 'POSTED' && t.transactionType !== 'PAYMENT_ONLY');

  // Final UAT Patch B: who may act on a transaction is the same predicate the
  // Post and Void controls already use (its source role, or Super Admin). A
  // Draft is editable only while it is an unallocated DRAFT. This is checked
  // again inside handleSaveEdit and, authoritatively, by the repository.
  const ownsTransaction = (t) => profile?.role === 'SUPER_ADMIN' || t.sourceRole === profile?.role;
  const canEdit = (t) => t.status === 'DRAFT' && !t.projectionId && ownsTransaction(t);
  const editingTx = editing ? transactions.find((t) => t.transactionId === editing) : null;
  const categoryOptions = [...new Set([form.category, ...CATEGORIES])];

  function openEdit(t) {
    setForm({
      category: t.category ?? 'Other',
      description: t.description ?? '',
      amount: String(t.amount ?? ''),
      transactionDate: t.transactionDate ?? EMPTY.transactionDate,
      referenceNumber: t.referenceNumber ?? '',
      invoiceNumber: t.invoiceNumber ?? '',
      transactionType: t.transactionType ?? 'COST',
      relatedTransactionId: t.relatedTransactionId ?? '',
    });
    setEditing(t.transactionId);
    setFormError('');
    setOpen(true);
  }

  function closeDialog() {
    setOpen(false);
    setEditing(null);
    setForm(EMPTY);
    setFormError('');
  }

  // B8: live duplicate check as the form changes, so the warning is visible
  // BEFORE the user attempts to submit -- not just as a rejection after.
  useEffect(() => {
    if (!open || !form.amount) { setDuplicate({ level: null, reasons: [] }); return; }
    let cancelled = false;
    // When editing, the Draft is excluded from its own comparison set.
    checkDuplicateTransaction(projectId, { ...form, amount: Number(form.amount), sourceRole: profile?.role }, editing ?? undefined).then((d) => {
      if (!cancelled) setDuplicate(d);
    });
    return () => { cancelled = true; };
  }, [open, form, projectId, profile?.role, editing]);

  async function handleCreate() {
    if (!form.description.trim()) { setFormError('Description is required.'); return; }
    // Final UAT Patch B: the shared Amount rule (the repository enforces it
    // again). No more silent return on a bad amount.
    try { parseAmount(form.amount); } catch (err) { setFormError(err.message); return; }
    if (form.transactionType === 'PAYMENT_ONLY' && !form.relatedTransactionId) return;
    setError('');
    setFormError('');
    try {
      await createCostTransaction(projectId, {
        ...form,
        amount: Number(form.amount),
        sourceRole: profile?.role,
        createdBy: profile?.displayName ?? profile?.name ?? 'Unknown',
        relatedTransactionId: form.transactionType === 'PAYMENT_ONLY' ? form.relatedTransactionId : null,
      });
      closeDialog();
      load();
      onDataChanged?.();
    } catch (err) {
      // B9: strong duplicates are blocked by the repository, not just
      // warned about -- this is the block taking effect. Shown inside the
      // dialog, next to the form, instead of behind it.
      setFormError(err.message);
    }
  }

  // Final UAT Patch B: save an edit to an unallocated DRAFT. Only the six
  // editable fields are sent (never the whole form or transaction). Eligibility
  // is re-checked here against the freshly loaded record -- not just by hiding
  // the Edit button -- and again by the repository.
  async function handleSaveEdit() {
    const tx = transactions.find((t) => t.transactionId === editing);
    if (!tx || !canEdit(tx)) {
      setFormError('This transaction can no longer be edited: it must be an unallocated DRAFT owned by your role.');
      load();
      return;
    }
    if (!form.description.trim()) { setFormError('Description is required.'); return; }
    let amount;
    try { amount = parseAmount(form.amount); } catch (err) { setFormError(err.message); return; }
    setFormError('');
    try {
      await updateDraftCostTransaction(projectId, editing, {
        category: form.category,
        description: form.description,
        amount,
        transactionDate: form.transactionDate,
        referenceNumber: form.referenceNumber,
        invoiceNumber: form.invoiceNumber,
      }, { role: profile?.role, name: profile?.displayName ?? profile?.name ?? 'Unknown' });
      closeDialog();
      load();
      onDataChanged?.();
    } catch (err) {
      setFormError(err.message);
      load(); // the record may have changed (posted/allocated) since it was loaded
    }
  }

  async function handlePost(transactionId) {
    const tx = transactions.find((t) => t.transactionId === transactionId);
    if (!(profile?.role === 'SUPER_ADMIN' || tx?.sourceRole === profile?.role)) return; // defense in depth, not just a hidden button
    try {
      await postCostTransaction(projectId, transactionId, profile?.displayName ?? profile?.name);
      load();
      onDataChanged?.();
    } catch (err) {
      setError(err.message);
    }
  }

  async function handleVoid() {
    if (!voidReason.trim()) return;
    const tx = transactions.find((t) => t.transactionId === voidTarget);
    if (!(profile?.role === 'SUPER_ADMIN' || tx?.sourceRole === profile?.role)) return;
    await voidCostTransaction(projectId, voidTarget, { voidedBy: profile?.displayName ?? profile?.name, voidReason });
    setVoidTarget(null);
    setVoidReason('');
    load();
    onDataChanged?.();
  }

  return (
    <Stack spacing={2}>
      <Stack direction="row" sx={{ justifyContent: 'space-between', alignItems: 'center' }}>
        <Typography variant="body2" color="text.secondary">
          Actual Cost = SUM of POSTED transactions only. DRAFT and VOID never affect it.
        </Typography>
        {canCreate && (
          <Button size="small" startIcon={<AddRoundedIcon />} onClick={() => setOpen(true)}>
            New Transaction
          </Button>
        )}
      </Stack>

      {error && <Alert severity="error" onClose={() => setError('')}>{error}</Alert>}

      <Paper sx={{ overflowX: 'auto' }}>
        <Box component="table" sx={{ width: '100%', borderCollapse: 'collapse', '& th, & td': { textAlign: 'left', p: 1.5, borderBottom: '1px solid', borderColor: 'divider', fontSize: 14 }, '& th': { color: 'text.secondary', fontSize: 12, textTransform: 'uppercase' } }}>
          <thead>
            <tr><th>Transaction ID</th><th>Date</th><th>Category</th><th>Description</th><th>Amount</th><th>Type</th><th>Source</th><th>Status</th><th></th></tr>
          </thead>
          <tbody>
            {transactions.map((t) => (
              <tr key={t.transactionId}>
                <td style={{ fontFamily: 'JetBrains Mono, monospace' }}>{t.transactionId}</td>
                <td>{t.transactionDate}</td>
                <td>{t.category}</td>
                <td>{t.description}</td>
                <td>{t.currency} {Number(t.amount).toLocaleString()}</td>
                <td>
                  {t.transactionType === 'PAYMENT_ONLY' ? (
                    <Chip size="small" label={`Payment for ${t.relatedTransactionId}`} variant="outlined" color="info" />
                  ) : (
                    <Chip size="small" label="Cost" variant="outlined" />
                  )}
                </td>
                <td>{t.sourceRole}</td>
                <td><Chip size="small" label={t.status} color={STATUS_COLOR[t.status]} variant="outlined" /></td>
                <td>
                  {canEdit(t) && (
                    <Button size="small" onClick={() => openEdit(t)}>Edit</Button>
                  )}
                  {t.status === 'DRAFT' && (profile?.role === 'SUPER_ADMIN' || t.sourceRole === profile?.role) && (
                    <Button size="small" onClick={() => handlePost(t.transactionId)}>Post</Button>
                  )}
                  {t.status === 'POSTED' && (profile?.role === 'SUPER_ADMIN' || t.sourceRole === profile?.role) && (
                    <Button size="small" color="error" disabled={!!t.projectionId} title={t.projectionId ? 'Allocated to a Payment Projection -- frozen' : undefined} onClick={() => setVoidTarget(t.transactionId)}>Void</Button>
                  )}
                  {t.status === 'VOID' && (
                    <Typography variant="caption" color="text.secondary">Reason: {t.voidReason}</Typography>
                  )}
                </td>
              </tr>
            ))}
          </tbody>
        </Box>
      </Paper>

      <Dialog open={open} onClose={closeDialog} fullWidth maxWidth="sm">
        <DialogTitle>{editing ? 'Edit Cost Transaction (DRAFT)' : 'New Cost Transaction (DRAFT)'}</DialogTitle>
        <DialogContent>
          <Stack spacing={2} sx={{ pt: 1 }}>
            {formError && <Alert severity="error">{formError}</Alert>}
            <TextField select label="Category" value={form.category} onChange={(e) => setForm((f) => ({ ...f, category: e.target.value }))} fullWidth>
              {categoryOptions.map((c) => <MenuItem key={c} value={c}>{c}</MenuItem>)}
            </TextField>
            <TextField label="Description" value={form.description} onChange={(e) => setForm((f) => ({ ...f, description: e.target.value }))} fullWidth />
            <Stack direction="row" spacing={2}>
              <TextField label="Amount (IDR)" type="number" value={form.amount} onChange={(e) => setForm((f) => ({ ...f, amount: e.target.value }))} fullWidth />
              <TextField label="Transaction Date" type="date" value={form.transactionDate} onChange={(e) => setForm((f) => ({ ...f, transactionDate: e.target.value }))} fullWidth slotProps={{ inputLabel: { shrink: true } }} />
            </Stack>
            <Stack direction="row" spacing={2}>
              <TextField label="Reference Number" value={form.referenceNumber} onChange={(e) => setForm((f) => ({ ...f, referenceNumber: e.target.value }))} fullWidth />
              <TextField label="Invoice Number" value={form.invoiceNumber} onChange={(e) => setForm((f) => ({ ...f, invoiceNumber: e.target.value }))} fullWidth />
            </Stack>
            {editing ? (
              <Typography variant="caption" color="text.secondary">
                Transaction {editing} \u00b7 source role: {editingTx?.sourceRole}. The transaction ID, source role, type and related transaction cannot be changed -- if the type or related transaction is wrong, create a new Draft.
              </Typography>
            ) : (
              <Typography variant="caption" color="text.secondary">Source role: {profile?.role} (recorded automatically -- cannot be changed here)</Typography>
            )}
            {isFinance && !editing && (
              <>
                <TextField
                  select label="Transaction Type" value={form.transactionType}
                  onChange={(e) => setForm((f) => ({ ...f, transactionType: e.target.value, relatedTransactionId: '' }))}
                  helperText="Cost = a new incurred expense. Payment for Existing Cost = settling a cost already on the ledger -- does NOT add to Actual Cost again."
                  fullWidth
                >
                  <MenuItem value="COST">Cost (new incurred expense)</MenuItem>
                  <MenuItem value="PAYMENT_ONLY">Payment for Existing Cost (no double counting)</MenuItem>
                </TextField>
                {form.transactionType === 'PAYMENT_ONLY' && (
                  <TextField
                    select label="Settles Which Cost Transaction" value={form.relatedTransactionId}
                    onChange={(e) => setForm((f) => ({ ...f, relatedTransactionId: e.target.value }))}
                    fullWidth
                  >
                    {settleableTransactions.map((t) => (
                      <MenuItem key={t.transactionId} value={t.transactionId}>
                        {t.transactionId} \u2014 {t.description} ({t.currency} {Number(t.amount).toLocaleString()})
                      </MenuItem>
                    ))}
                  </TextField>
                )}
              </>
            )}
            {duplicate.level === 'STRONG' && (
              <Alert severity="error">
                Strong duplicate detected -- this will be BLOCKED on submit.
                {duplicate.reasons.map((r) => <div key={r}>{r}</div>)}
              </Alert>
            )}
            {duplicate.level === 'POSSIBLE' && (
              <Alert severity="warning">
                Possible duplicate -- please review before posting.
                {duplicate.reasons.map((r) => <div key={r}>{r}</div>)}
              </Alert>
            )}
          </Stack>
        </DialogContent>
        <DialogActions>
          <Button onClick={closeDialog}>Cancel</Button>
          <Button variant="contained" onClick={editing ? handleSaveEdit : handleCreate}>{editing ? 'Save Changes' : 'Save as Draft'}</Button>
        </DialogActions>
      </Dialog>

      <Dialog open={!!voidTarget} onClose={() => setVoidTarget(null)} fullWidth maxWidth="xs">
        <DialogTitle>Void Transaction</DialogTitle>
        <DialogContent>
          <Typography variant="body2" color="text.secondary" sx={{ mb: 2 }}>
            The transaction remains visible for audit -- this does not delete it.
          </Typography>
          <TextField label="Void Reason (required)" value={voidReason} onChange={(e) => setVoidReason(e.target.value)} fullWidth multiline minRows={2} />
        </DialogContent>
        <DialogActions>
          <Button onClick={() => setVoidTarget(null)}>Cancel</Button>
          <Button variant="contained" color="error" disabled={!voidReason.trim()} onClick={handleVoid}>Void</Button>
        </DialogActions>
      </Dialog>
    </Stack>
  );
}

// Sensible defaults applied to a brand-new project created via the form —
// operational fields (progress, health, SPI, issues, manpower) aren't part
// of the create form and start from a clean baseline.
export function createBlankProject(formValues) {
  return {
    id: typeof crypto !== 'undefined' && crypto.randomUUID ? crypto.randomUUID() : `proj-${Date.now()}`,
    healthStatus: 'Good',
    progress: 0,
    spi: 1.0,
    openIssues: 0,
    manpower: 0,
    ...formValues,
    // FT-9A-01: projectManagerId is now supplied by the form itself (a
    // real userId from userRepository.getUsers(), selected in
    // ProjectFormDialog) -- it must be preserved, never overwritten by the
    // legacy name-based pmId() lookup. That lookup is kept ONLY as a
    // fallback for any caller that still doesn't provide a real
    // projectManagerId (there should be none going forward).
    projectManagerId: formValues.projectManagerId || pmId(formValues.projectManager),
  };
}

// Used by the Action Menu's "Duplicate" action — clones a project with a
// fresh id/code so it appears as a distinct row without touching the
// original.
export function duplicateProject(project) {
  return {
    ...project,
    id: typeof crypto !== 'undefined' && crypto.randomUUID ? crypto.randomUUID() : `proj-${Date.now()}`,
    projectCode: `${project.projectCode}-COPY`,
    projectName: `${project.projectName} (Copy)`,
    status: 'Planning',
    progress: 0,
    spi: 1.0,
    openIssues: 0,
  };
}
